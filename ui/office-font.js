const FONTS = { 5: { g: F5, w: 5, h: 7 }, 3: { g: F3, w: 3, h: 5 } };

export function textWidth(s, size = 3) { const f = FONTS[size]; return String(s).length * (f.w + 1) - 1; }

/** Draw text; align left | center | right at x; a 1px shadow keeps it readable over the scene. */
export function text(img, s, x, y, color, { size = 3, align = "left", shadow = "#0b0b0e" } = {}) {
  const f = FONTS[size], str = String(s).toUpperCase(), w = textWidth(str, size);
  let cx = Math.round(align === "center" ? x - w / 2 : align === "right" ? x - w : x);
  y = Math.round(y);
  for (const ch of str) {
    const g = f.g[ch];
    if (g) {
      const rows = g.split(" ");
      if (shadow) rows.forEach((row, j) => [...row].forEach((b, i) => { if (b === "1") { px(img, cx + i + 1, y + j + 1, shadow, 0.85); } }));
      rows.forEach((row, j) => [...row].forEach((b, i) => { if (b === "1") px(img, cx + i, y + j, color); }));
    }
    cx += f.w + 1;
  }
  return w;
}
/** Fit a string into n characters (an ellipsis as two dots). */
export const fit = (s, n) => { s = String(s).toUpperCase(); return s.length <= n ? s : `${s.slice(0, n - 2).trimEnd()}..`; };
